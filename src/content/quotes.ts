/** Day of the year, 0 to 364 (31 December in a leap year shares the last quote). */
export function dayOfYear(d: Date = new Date()): number {
  const start = new Date(d.getFullYear(), 0, 1);
  const n = Math.floor((new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() - start.getTime()) / 86400000);
  return Math.min(364, Math.max(0, n));
}

export function quoteFor(d: Date, lang: 'en' | 'tn'): string {
  return (lang === 'tn' ? QUOTES_TN : QUOTES_EN)[dayOfYear(d)];
}
